import {makeDB} from './d1shim.mjs';
import {onRequest} from '../functions/api/[[path]].js';
const DB=makeDB();
const call=async(method,path,body,code,env)=>{const r=await onRequest({request:new Request('http://x'+path,{method,headers:{'content-type':'application/json',...(code?{'x-admin-code':code}:{})},body:body?JSON.stringify(body):undefined}),env:env||{DB,ADMIN_CODE:'sekret-123'}});return{s:r.status,j:await r.json()}};
const ok=(c,m)=>{console.log(c?'PASS':'FAIL',m);if(!c)process.exitCode=1};
const hit=(ev,vid,src='direct',game='fruit')=>call('POST','/api/hit',{ev,vid,src,game});
let r=await call('GET','/api/stats',null,'sekret-123',{DB});ok(r.s===503,'stats refuse when ADMIN_CODE is not set');
r=await call('GET','/api/stats',null,null);ok(r.s===401,'no code = refused');
r=await call('GET','/api/stats',null,'wrong');ok(r.s===401,'wrong code = refused');
r=await hit('visit','phoneAAAA1111','facebook');ok(r.j.ok,'visit counted');
await hit('visit','phoneAAAA1111','facebook');await hit('visit','phoneBBBB2222','telegram');await hit('visit','phoneCCCC3333');
await hit('play','phoneAAAA1111','facebook');await hit('play','phoneAAAA1111','facebook');await hit('play','phoneBBBB2222','telegram');
await hit('install','phoneAAAA1111','facebook');await hit('share','phoneBBBB2222','telegram');await hit('fb','phoneCCCC3333');
await hit('visit','phoneDDDD4444','direct','sort');
r=await call('POST','/api/hit',{ev:'hack',vid:'phoneAAAA1111'});ok(r.s===400,'unknown event refused');
r=await call('POST','/api/hit',{ev:'visit',vid:'x'});ok(r.s===400,'too-short id refused');
r=await call('GET','/api/stats?days=7',null,'sekret-123');const d=r.j;
ok(r.s===200&&d.visitors===4,'4 different phones counted once each (got '+d.visitors+')');
ok(d.plays===3&&d.installs===1&&d.shares===1&&d.fbClicks===1,'plays 3, install 1, share 1, facebook click 1');
ok(d.sources.find(s=>s.src==='facebook').c===1&&d.sources.find(s=>s.src==='telegram').c===1,'sources split by Facebook / Telegram');
ok(d.games.fruit.visitors===3&&d.games.sort.visitors===1&&d.games.fruit.plays===3,'numbers split per game');
const today=Object.keys(d.perDay).pop();ok(d.perDay[today].visitors===4&&d.perDay[today].plays===3,'today bar is right');
ok(!JSON.stringify(d).includes('phoneAAAA1111'),'phone ids are never shown in the report');
for(let i=0;i<310;i++)await hit('play','floodFLOOD9999');
r=await call('GET','/api/stats',null,'sekret-123');ok(r.j.plays<=3+300,'one phone cannot flood the numbers (plays '+r.j.plays+')');
r=await call('GET','/api/nothing');ok(r.s===404,'unknown route 404');
